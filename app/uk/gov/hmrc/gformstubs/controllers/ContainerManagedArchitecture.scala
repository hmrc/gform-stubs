  def postVatParcelsC2C() = Action.async { _ =>
    val instant: String =
      ZonedDateTime.ofInstant(Instant.now(), ZoneOffset.UTC).truncatedTo(ChronoUnit.SECONDS).toString

    Future.successful(
      Ok(
        s"""
           |{
           |  "success": {
